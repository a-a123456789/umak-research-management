import pg from 'pg';
import { createApp } from './app.js';
import {readFileSync} from 'node:fs';
import https from 'node:https';
import http from 'node:http';
import {databaseConfig} from './security/database-config.js';
import {configuredStore} from './storage/s3.js';
import {clamScanner} from './storage/scanner.js';
if(process.env.NODE_ENV==='production'&&(!process.env.TLS_CERT_FILE||!process.env.TLS_KEY_FILE))throw Error('Production API TLS certificate and key are required');
const db=new pg.Pool(databaseConfig());
await db.query('SELECT 1');
const app=createApp(db,{objectStore:configuredStore(),scanner:clamScanner()});
const server=(process.env.TLS_CERT_FILE?https.createServer({cert:readFileSync(process.env.TLS_CERT_FILE),key:readFileSync(process.env.TLS_KEY_FILE),minVersion:'TLSv1.3'},app):http.createServer(app));
server.requestTimeout=60_000;server.headersTimeout=15_000;
server.listen(Number(process.env.PORT||3000),process.env.HOST||'127.0.0.1',()=>console.log('CRM API listening on port '+(process.env.PORT||3000)));
for(const signal of ['SIGINT','SIGTERM']) process.on(signal,()=>server.close(async()=>{await db.end();process.exit(0);}));
