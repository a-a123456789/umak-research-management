CREATE TABLE IF NOT EXISTS users (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email text UNIQUE NOT NULL,
 password_hash text NOT NULL,
 role text NOT NULL CHECK (role IN ('student','staff'))
);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash text PRIMARY KEY, user_id integer NOT NULL REFERENCES users ON DELETE CASCADE,
 expires_at timestamptz NOT NULL
);
CREATE TABLE IF NOT EXISTS research_records (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 author_id integer NOT NULL REFERENCES users ON DELETE CASCADE,
 title text NOT NULL CHECK (length(title) BETWEEN 1 AND 200),
 abstract text NOT NULL DEFAULT '',
 status text NOT NULL CHECK (status IN ('Draft','Approved'))
);
CREATE TABLE IF NOT EXISTS consents (
 id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 user_id integer NOT NULL REFERENCES users ON DELETE CASCADE,
 policy_version text NOT NULL, choices jsonb NOT NULL,
 recorded_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE IF NOT EXISTS deletion_requests (
 id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 user_id integer REFERENCES users ON DELETE SET NULL,
 status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','completed')),
 requested_at timestamptz NOT NULL DEFAULT clock_timestamp(), completed_at timestamptz
);
CREATE UNIQUE INDEX IF NOT EXISTS one_pending_deletion ON deletion_requests(user_id) WHERE status='pending';
CREATE TABLE IF NOT EXISTS audit_logs (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 actor_id integer REFERENCES users ON DELETE SET NULL,
 action text NOT NULL, recorded_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
